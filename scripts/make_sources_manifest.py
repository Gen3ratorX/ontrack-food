"""Regenerate knowledge_base/SOURCES.md and sources.json from document front-matter."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ontrack.rag.chunking import parse_front_matter  # noqa: E402

rows = []
for p in sorted((ROOT / "knowledge_base" / "docs").glob("*.md")):
    meta, _ = parse_front_matter(p.read_text(encoding="utf-8"))
    meta["file"] = f"docs/{p.name}"
    rows.append(meta)
(ROOT / "knowledge_base" / "sources.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False))
lines = ["# Knowledge-base sources", "", "Generated by `scripts/make_sources_manifest.py`. Every document carries its citation and licence in its front-matter.",
         "Documents with `index: false` are reference only and are not retrieved.", "",
         "| id | title | publisher | licence | url |", "|---|---|---|---|---|"]
for r in rows:
    lic = r.get("licence", "").replace("|", "/")
    flag = " (not indexed)" if r.get("index") == "false" else ""
    lines.append(f"| {r.get('id')}{flag} | {r.get('title')} | {r.get('publisher')} | {lic} | {r.get('url')} |")
(ROOT / "knowledge_base" / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(rows), "sources")
