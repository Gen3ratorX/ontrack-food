def main():
    out = Path(__file__).resolve().parents[1] / "data" / "classifier" / "triage_seed.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for label, items in (("general_education", GENERAL), ("needs_clinician", CLINICIAN), ("emergency", EMERGENCY)):
        for i, t in enumerate(items):
            rows.append({"id": f"{label[:3]}-{i:03d}", "text": t, "label": label, "synthetic": True,
                         "source": "OnTrack team synthetic seed v0.1 (AI-assisted draft)", "reviewed": False})
    with open(out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    from collections import Counter
    print(out, len(rows), Counter(r["label"] for r in rows))

if __name__ == "__main__":
    main()
